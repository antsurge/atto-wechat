package miniProgram

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"

	cerrors "github.com/antsurge/atto-wechat/core/errors"
	"github.com/antsurge/atto-wechat/core/response"
)

// checkEncryptedDataPath is the encrypted-data endpoint: it tells whether an
// encrypted payload was produced by WeChat for this mini program.
const (
	checkEncryptedDataPath          = "/wxa/business/checkencryptedmsg"
	CheckEncryptedDataDefaultErrMsg = "系统错误，请稍后再试"
)

// CheckEncryptedDataErrCodeMap holds the errcode descriptions WeChat documents
// for /wxa/business/checkencryptedmsg, keyed by the errcode as it appears in the
// reply.
//
// It is exported so callers can render a human-readable reason for an errcode
// without repeating the table themselves.
var CheckEncryptedDataErrCodeMap = map[int]string{
	-1:    "系统繁忙",
	1:     "加密数据不存在，或生成时间超过 3 天，或密钥不存在，或数据与 appid 不匹配",
	40097: "参数错误",
	44002: "POST 数据包为空",
	47001: "JSON 数据格式错误，或缺少参数",
}

// CheckEncryptedDataResponse is the reply of /wxa/business/checkencryptedmsg.
//
// The structure keeps the two kinds of parameters apart: the embedded common
// header is what every WeChat API returns (errcode/errmsg), while the fields
// below are specific to this endpoint.
type CheckEncryptedDataResponse struct {
	// Common reply parameters.
	response.WechatResponse

	// Business reply parameters.
	//
	// Valid spells "vaild" in the wire format: WeChat shipped the field with
	// that typo and still returns it, so the tag must match the reply.
	Valid      bool  `json:"vaild"`
	CreateTime int64 `json:"create_time"`
}

// OK reports whether the payload was confirmed to be generated by WeChat.
//
// A reply with errcode 0 and Valid false is not an error: it means WeChat
// looked at the hash and answered that the data is not genuine.
func (r *CheckEncryptedDataResponse) OK() bool {
	return r != nil && r.ErrCode == 0 && r.Valid
}

// CheckEncryptedDataErrMsg returns the description of a checkEncryptedData error.
func CheckEncryptedDataErrMsg(code int) string {
	if msg, ok := CheckEncryptedDataErrCodeMap[code]; ok {
		return msg
	}
	return CheckEncryptedDataDefaultErrMsg
}

// CheckEncryptedDataError turns the errcode from the reply into an error.
//
// The errcode itself is the error code, and its description comes straight from
// CheckEncryptedDataErrCodeMap. An undocumented errcode has no agreed meaning, so
// it falls back to a generic message rather than exposing WeChat's raw errmsg.
func CheckEncryptedDataError(r *CheckEncryptedDataResponse) error {
	return errors.New(CheckEncryptedDataErrMsg(r.ErrCode))
}

// EncryptedMsgHash returns the hex encoded sha256 of the encrypted payload, as
// the encrypted_msg_hash parameter expects it.
func EncryptedMsgHash(encryptedData []byte) string {
	sum := sha256.Sum256(encryptedData)

	return hex.EncodeToString(sum[:])
}

// CheckEncryptedData asks WeChat whether an encrypted payload was generated by
// it for this mini program.
//
// Only encrypted phone numbers are supported, and only data generated in the
// last three days can be verified. CheckEncryptedData takes the sha256 of the
// encrypted data (EncryptedMsgHash computes it), not the data itself.
//
// The result is a hint, not a decryption: Valid false means WeChat does not
// recognise the hash, which is how forged or stale payloads are rejected.
func (a *Application) CheckEncryptedData(
	ctx context.Context,
	encryptedMsgHash string,
) (*CheckEncryptedDataResponse, error) {
	if encryptedMsgHash == "" {
		return nil, cerrors.New(
			cerrors.CodeInvalidArgument,
			"miniprogram: encrypted_msg_hash must not be empty",
		)
	}

	resp, err := a.api.PostJSON(ctx, checkEncryptedDataPath, nil, map[string]string{
		"encrypted_msg_hash": encryptedMsgHash,
	})
	if err != nil {
		return nil, err
	}

	var result CheckEncryptedDataResponse
	if err := resp.DecodeJSON(&result); err != nil {
		return nil, err
	}

	return &result, nil
}
